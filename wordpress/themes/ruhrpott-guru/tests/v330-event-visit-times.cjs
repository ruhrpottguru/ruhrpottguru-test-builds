'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
process.env.TZ='Europe/Berlin';
const src=fs.readFileSync(path.join(__dirname,'../src/react-app/views.js'),'utf8');
const start=src.indexOf('  function homeEventDayAccess('),end=src.indexOf('  function useCategoryItems(',start);
assert(start>0&&end>start);
const ctx={Date};vm.createContext(ctx);
vm.runInContext(src.slice(start,end)+'\nthis.fn={access:homeEventDayAccess,match:homeEventMatchesTime,hint:homeEventTimeHint,priority:eventPriorityCompare};',ctx);
const {access,match,hint,priority}=ctx.fn;
const date=(day,h,m=0)=>new Date(2026,9,day,h,m);
const exhibition=(title,desc)=>({title,city:'Wesel',distanceKm:0.5,start:date(1,9),end:date(26,15),allDay:false,description:desc,dayHours:'',visitorHours:''});
const spielarten=exhibition('Spielarten der Abstraktion','Dritter Ort Stadtwerketurm Brandstraße 44 Wesel\n\nÖffnungszeiten\nMO-DO | 9-16 Uhr FR | 9-14 Uhr\nund während vieler weiterer Veranstaltungen');
const sundayLate=date(11,22,15),mondayBefore=date(12,8,30),mondayOpen=date(12,11),mondayAfter=date(12,16,1),fridayOpen=date(16,13);
assert.equal(access(spielarten,sundayLate).state,'closed','explicit non-Sunday regular opening recognized');
assert(!match(spielarten,'now',sundayLate));assert(!match(spielarten,'today',sundayLate));
assert(match(spielarten,'tomorrow',sundayLate),'tomorrow fallback rule preserved');
assert.equal(access(spielarten,mondayBefore).state,'confirmed');
assert(!match(spielarten,'now',mondayBefore),'future opening not yet open now');
assert(match(spielarten,'today',mondayBefore),'opens later today');
assert.equal(access(spielarten,mondayOpen).until,'16:00');
assert(match(spielarten,'now',mondayOpen));assert(match(spielarten,'today',mondayOpen));
assert.equal(hint(spielarten,'now',mondayOpen),'Reguläre Besuchszeit · bis 16:00');
assert(!match(spielarten,'now',mondayAfter));assert(!match(spielarten,'today',mondayAfter));
assert.equal(access(spielarten,fridayOpen).until,'14:00','Friday hours parsed');
const unknown=exhibition('Unknown opening hours','This event spans multiple weeks.');
assert.equal(access(unknown,sundayLate).state,'unknown');
assert(match(unknown,'now',sundayLate),'unknown time neutral fallback, no silent exclusion');
assert(match(unknown,'today',sundayLate),'unknown long event is shown as uncertainty fallback');
assert.equal(hint(unknown,'today',sundayLate),'Laufende Veranstaltung · Öffnungszeiten unbekannt');
const justFree=exhibition('Free to enter','frei zugänglich, kein Eintritt');
assert.equal(access(justFree,sundayLate).state,'unknown','free access alone is not guaranteed 24h');
const fullyPublic=exhibition('Confirmed 24/7','Öffnungszeiten: jederzeit frei zugänglich, rund um die Uhr.');
assert.equal(access(fullyPublic,sundayLate).state,'confirmed');
assert(match(fullyPublic,'now',sundayLate));
assert.equal(hint(fullyPublic,'now',sundayLate),'Laut Angaben jederzeit zugänglich');
const nearby={...unknown,title:'Other city',city:'Oberhausen',distanceKm:23};
const next={title:'Monday concrete',city:'Wesel',start:date(12,11),end:date(12,13),distanceKm:1};
const lateEvent={title:'Tonight concrete',city:'Rheinberg',start:date(11,22,30),end:date(11,23,59),distanceKm:10};
const all=[unknown,spielarten,fullyPublic,nearby,lateEvent,next];
all.sort(priority(all,'today',{city:'Wesel'},sundayLate));
assert.equal(all[0].title,'Tonight concrete','concrete before all ongoing');
assert.equal(all[1].title,'Confirmed 24/7','confirmed accessible ongoing before unknowns');
assert.equal(all[2].title,'Unknown opening hours','same-city unknown fallback before neighbouring city');
assert.equal(all[3].title,'Other city','unknown fallback remains under city/distance ordering');
assert.equal(all[4].title,'Spielarten der Abstraktion','explicitly closed does not enter chosen period');
assert.equal(all[5].title,'Monday concrete','future event still in full catalogue');
assert(src.includes('visible=visible.filter(x=>homeEventMatchesTime(x,eventWindow,now))'),'Home only time-matched events');
assert(src.includes("h('h2',null,'Weitere Veranstaltungen')"),'Full category keeps additional events');
console.log('PASS v330 event visiting hours: source phrase, regular weekdays, time cutoffs, uncertain fallback, 24h proof, priority, full list.');
